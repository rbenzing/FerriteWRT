//! `RadioPlan` -> hostapd.conf (one file per radio, multi-BSS). Output is deterministic.

use std::fmt::Display;
use std::path::PathBuf;

use owr_common::paths::RUN_DIR;

use crate::channel::{center_channel, ht40_sign};
use crate::model::{ApPlan, Band, Channel, RadioPlan, Security, Standard};
use crate::validate::Issue;

/// hostapd control-socket directory (`<RUN_DIR>/hostapd`, see [`owr_common::paths::RUN_DIR`]);
/// one socket per BSS.
pub fn ctrl_dir() -> PathBuf {
    PathBuf::from(format!("{RUN_DIR}/hostapd"))
}

/// Why a plan could not be rendered.
#[derive(Debug, Clone, PartialEq, Eq, thiserror::Error)]
pub enum RenderError {
    #[error("invalid radio plan: {}", join_issues(.0))]
    Invalid(Vec<Issue>),
}

fn join_issues(issues: &[Issue]) -> String {
    issues
        .iter()
        .map(ToString::to_string)
        .collect::<Vec<_>>()
        .join("; ")
}

/// Line-oriented writer.
#[derive(Default)]
struct Conf(String);

impl Conf {
    fn kv(&mut self, key: &str, value: impl Display) {
        self.0.push_str(key);
        self.0.push('=');
        self.0.push_str(&value.to_string());
        self.0.push('\n');
    }

    fn raw(&mut self, line: &str) {
        self.0.push_str(line);
        self.0.push('\n');
    }
}

/// Render a complete hostapd.conf for `plan`.
///
/// **The output contains passphrases in clear text**; treat it as a secret (wipe it after
/// use, never log it). [`crate::write_config`] does so and writes the file mode 0600.
///
/// The plan is validated first; invalid plans never produce output. Radio-wide keys come
/// first (hostapd applies the section before the first `bss=` to the first BSS and the
/// radio), followed by one block per AP: `interface=` for the first, `bss=` for the rest.
pub fn render_hostapd(plan: &RadioPlan) -> Result<String, RenderError> {
    plan.validate().map_err(RenderError::Invalid)?;
    let mut c = Conf::default();
    c.raw("# Generated by owr-wifi. Do not edit; changes are overwritten.");
    render_radio(&mut c, plan);
    for (i, ap) in plan.aps.iter().enumerate() {
        c.raw("");
        c.kv(if i == 0 { "interface" } else { "bss" }, &ap.ifname);
        render_bss(&mut c, ap);
    }
    Ok(c.0)
}

fn render_radio(c: &mut Conf, plan: &RadioPlan) {
    let band = plan.band;
    c.kv("driver", "nl80211");
    c.kv("country_code", &plan.country);
    c.kv("ieee80211d", 1);
    if band == Band::G5 {
        // DFS radar detection / channel-availability checks.
        c.kv("ieee80211h", 1);
    }
    c.kv("hw_mode", if band == Band::G2 { 'g' } else { 'a' });
    match plan.channel {
        Channel::Auto => {
            c.kv("channel", 0); // ACS
            if band == Band::G5 {
                c.kv("acs_exclude_dfs", 1);
            }
        }
        Channel::Fixed(ch) => c.kv("channel", ch),
    }
    if band == Band::G6 {
        // 6 GHz global operating class: 131/132/133/134 for 20/40/80/160 MHz.
        c.kv("op_class", op_class_6g(plan.width_mhz));
    }
    c.kv("beacon_int", 100);
    c.kv("logger_syslog", -1);
    c.kv("logger_syslog_level", 2);
    c.kv("logger_stdout", -1);
    c.kv("logger_stdout_level", 2);

    if plan.has(Standard::N) {
        render_ht(c, plan);
    }
    if plan.has(Standard::Ac) {
        render_vht(c, plan);
    }
    if plan.has(Standard::Ax) {
        render_he(c, plan);
    }
    if plan.has(Standard::Be) {
        c.kv("ieee80211be", 1);
    }
}

fn op_class_6g(width_mhz: u16) -> u16 {
    match width_mhz {
        20 => 131,
        40 => 132,
        80 => 133,
        _ => 134,
    }
}

/// `*_oper_chwidth`: 0 for 20/40 MHz, 1 for 80, 2 for 160.
fn oper_chwidth(width_mhz: u16) -> u8 {
    match width_mhz {
        80 => 1,
        160 => 2,
        _ => 0,
    }
}

/// Centre-channel index for fixed 80/160 MHz channels; absent for Auto (ACS decides)
/// and for 20/40 MHz where hostapd derives it from the HT secondary channel.
fn seg0(plan: &RadioPlan) -> Option<u16> {
    match plan.channel {
        Channel::Fixed(ch) => center_channel(plan.band, ch, plan.width_mhz),
        Channel::Auto => None,
    }
}

fn render_ht(c: &mut Conf, plan: &RadioPlan) {
    let wide = plan.width_mhz >= 40;
    let ht40 = match (wide, plan.channel) {
        (false, _) => String::new(),
        (true, Channel::Fixed(ch)) => format!("[HT40{}]", ht40_sign(plan.band, ch)),
        // ACS may land on either side of the 2.4 GHz band, so allow both secondaries.
        (true, Channel::Auto) if plan.band == Band::G2 => "[HT40+][HT40-]".to_owned(),
        (true, Channel::Auto) => "[HT40+]".to_owned(),
    };
    let gi40 = if wide { "[SHORT-GI-40]" } else { "" };
    let caps = format!("{ht40}[SHORT-GI-20]{gi40}[TX-STBC][RX-STBC1][LDPC][MAX-AMSDU-7935]");
    c.kv("ieee80211n", 1);
    c.kv("ht_capab", caps);
    c.kv("require_ht", 0);
}

fn render_vht(c: &mut Conf, plan: &RadioPlan) {
    // Full set only for drivers known to implement it (mt76); others get the
    // conservative subset every VHT radio supports.
    let wide160 = plan.width_mhz == 160;
    let caps = if plan.driver_quirks.mt76 {
        let gi160 = if wide160 { "[SHORT-GI-160]" } else { "" };
        format!(
            "[RXLDPC][SHORT-GI-80]{gi160}[TX-STBC-2BY1][SU-BEAMFORMER][SU-BEAMFORMEE]\
             [MU-BEAMFORMER][MU-BEAMFORMEE][RX-ANTENNA-PATTERN][TX-ANTENNA-PATTERN]\
             [RX-STBC-1][BF-ANTENNA-4][MAX-A-MPDU-LEN-EXP7][MAX-MPDU-11454]"
        )
    } else {
        "[RXLDPC][SHORT-GI-80][TX-STBC-2BY1][RX-STBC-1][MAX-A-MPDU-LEN-EXP7][MAX-MPDU-11454]"
            .to_owned()
    };
    // `vht_oper_chwidth=2` is only honoured when the capability set advertises 160 MHz.
    let caps = if wide160 {
        format!("{caps}[VHT160]")
    } else {
        caps
    };
    c.kv("ieee80211ac", 1);
    c.kv("vht_oper_chwidth", oper_chwidth(plan.width_mhz));
    if let Some(centre) = seg0(plan) {
        c.kv("vht_oper_centr_freq_seg0_idx", centre);
    }
    c.kv("vht_capab", caps);
}

fn render_he(c: &mut Conf, plan: &RadioPlan) {
    c.kv("ieee80211ax", 1);
    c.kv("he_oper_chwidth", oper_chwidth(plan.width_mhz));
    if let Some(centre) = seg0(plan) {
        c.kv("he_oper_centr_freq_seg0_idx", centre);
    }
    c.kv("he_su_beamformer", 1);
    c.kv("he_su_beamformee", 1);
    c.kv("he_mu_beamformer", u8::from(plan.driver_quirks.mt76));
    // validate() guarantees at least one AP.
    let first_ssid = plan.aps.first().map_or("", |ap| ap.ssid.as_str());
    c.kv("he_bss_color", bss_color(first_ssid));
    c.kv("he_default_pe_duration", 4);
    c.kv("he_rts_threshold", 1023);
}

/// Deterministic BSS colour in 1..=63 from an FNV-1a hash of the SSID.
fn bss_color(ssid: &str) -> u32 {
    let hash = ssid.bytes().fold(0x811c_9dc5_u32, |h, b| {
        (h ^ u32::from(b)).wrapping_mul(0x0100_0193)
    });
    (hash % 63).saturating_add(1)
}

fn render_bss(c: &mut Conf, ap: &ApPlan) {
    c.kv("ctrl_interface", ctrl_dir().display());
    c.kv("ctrl_interface_group", 0);
    c.kv("ssid", &ap.ssid);
    if ap.hidden {
        c.kv("ignore_broadcast_ssid", 1);
    }
    if let Some(bridge) = &ap.bridge {
        c.kv("bridge", bridge);
    }
    if ap.isolate_clients {
        c.kv("ap_isolate", 1);
    }
    if let Some(max) = ap.max_clients {
        c.kv("max_num_sta", max);
    }
    if let Some(mac) = ap.mac {
        c.kv("bssid", mac);
    }
    c.kv("wmm_enabled", 1);
    c.kv("disassoc_low_ack", 1);
    c.kv("skip_inactivity_poll", 0);
    render_security(c, &ap.security);
}

fn render_security(c: &mut Conf, security: &Security) {
    match security {
        Security::Open => {
            c.kv("wpa", 0);
            c.kv("ieee80211w", 0);
        }
        Security::Wpa2Psk { passphrase } => {
            c.kv("wpa", 2);
            c.kv("wpa_key_mgmt", "WPA-PSK");
            c.kv("wpa_pairwise", "CCMP");
            c.kv("rsn_pairwise", "CCMP");
            c.kv("ieee80211w", 1);
            c.kv("wpa_passphrase", passphrase.as_str());
            // KRACK hardening: never retransmit EAPOL-Key frames with the same nonce.
            c.kv("wpa_disable_eapol_key_retries", 1);
        }
        Security::Wpa3Sae { passphrase } => {
            c.kv("wpa", 2);
            c.kv("wpa_key_mgmt", "SAE");
            c.kv("rsn_pairwise", "CCMP");
            c.kv("ieee80211w", 2);
            c.kv("sae_password", passphrase.as_str());
            c.kv("sae_require_mfp", 1);
            c.kv("sae_pwe", 2);
        }
        Security::Wpa2Wpa3Mixed { passphrase } => {
            c.kv("wpa", 2);
            c.kv("wpa_key_mgmt", "WPA-PSK SAE");
            c.kv("rsn_pairwise", "CCMP");
            c.kv("ieee80211w", 1);
            c.kv("sae_require_mfp", 1);
            c.kv("wpa_passphrase", passphrase.as_str());
            c.kv("sae_password", passphrase.as_str());
            c.kv("sae_pwe", 2);
            c.kv("wpa_disable_eapol_key_retries", 1);
        }
    }
}

#[cfg(test)]
mod tests {
    #![allow(clippy::indexing_slicing)]

    use zeroize::Zeroizing;

    use super::*;
    use crate::model::Quirks;
    use crate::validate::tests::{ap, plan_2g, plan_5g};

    fn pass(s: &str) -> Zeroizing<String> {
        Zeroizing::new(s.to_owned())
    }

    fn flint2_2g() -> RadioPlan {
        let mut main = ap("wlan0");
        main.ssid = "Flint2".into();
        main.security = Security::Wpa2Wpa3Mixed {
            passphrase: pass("flint2-main-pass"),
        };
        let mut guest = ap("wlan0-1");
        guest.ssid = "Flint2-Guest".into();
        guest.hidden = true;
        guest.isolate_clients = true;
        guest.bridge = Some("br-guest".into());
        guest.security = Security::Wpa2Wpa3Mixed {
            passphrase: pass("flint2-guest-pass"),
        };
        RadioPlan {
            phy: "phy0".into(),
            band: Band::G2,
            channel: Channel::Auto,
            width_mhz: 40,
            country: "US".into(),
            txpower_dbm: None,
            standards: vec![Standard::N, Standard::Ax],
            aps: vec![main, guest],
            driver_quirks: Quirks { mt76: true },
        }
    }

    fn flint2_5g() -> RadioPlan {
        let mut main = ap("wlan1");
        main.ssid = "Flint2-5G".into();
        main.security = Security::Wpa3Sae {
            passphrase: pass("flint2-5g-pass"),
        };
        RadioPlan {
            phy: "phy1".into(),
            band: Band::G5,
            channel: Channel::Fixed(36),
            width_mhz: 160,
            country: "US".into(),
            txpower_dbm: None,
            standards: vec![Standard::N, Standard::Ac, Standard::Ax],
            aps: vec![main],
            driver_quirks: Quirks { mt76: true },
        }
    }

    #[test]
    fn snapshot_flint2_radio0_2g() {
        insta::assert_snapshot!(render_hostapd(&flint2_2g()).unwrap());
    }

    #[test]
    fn snapshot_flint2_radio1_5g() {
        insta::assert_snapshot!(render_hostapd(&flint2_5g()).unwrap());
    }

    #[test]
    fn output_is_deterministic() {
        let p = flint2_2g();
        assert_eq!(
            render_hostapd(&p).unwrap(),
            render_hostapd(&p.clone()).unwrap()
        );
    }

    #[test]
    fn invalid_plan_is_rejected_without_output() {
        let mut p = flint2_2g();
        p.country = "us".into();
        assert!(matches!(render_hostapd(&p), Err(RenderError::Invalid(_))));
    }

    #[test]
    fn error_message_lists_issues() {
        let mut p = flint2_2g();
        p.aps.clear();
        let msg = render_hostapd(&p).unwrap_err().to_string();
        assert!(msg.contains("at least one AP"), "{msg}");
    }

    #[test]
    fn first_ap_is_interface_rest_are_bss() {
        let conf = render_hostapd(&flint2_2g()).unwrap();
        assert_eq!(conf.matches("\ninterface=wlan0\n").count(), 1);
        assert_eq!(conf.matches("\nbss=wlan0-1\n").count(), 1);
        assert!(!conf.contains("bss=wlan0\n"));
    }

    #[test]
    fn ht_capab_sign_follows_channel_2g() {
        let mut p = plan_2g();
        p.channel = Channel::Fixed(6);
        assert!(render_hostapd(&p).unwrap().contains("ht_capab=[HT40+]"));
        p.channel = Channel::Fixed(9);
        assert!(render_hostapd(&p).unwrap().contains("ht_capab=[HT40-]"));
        // ACS on 2.4 GHz may pick either side.
        p.channel = Channel::Auto;
        assert!(
            render_hostapd(&p)
                .unwrap()
                .contains("ht_capab=[HT40+][HT40-][SHORT-GI-20]")
        );
        // 5 GHz ACS keeps a single deterministic secondary.
        let mut p5 = plan_5g();
        p5.width_mhz = 40;
        p5.channel = Channel::Auto;
        assert!(
            render_hostapd(&p5)
                .unwrap()
                .contains("ht_capab=[HT40+][SHORT-GI-20]")
        );
    }

    #[test]
    fn vht160_capability_only_for_160_mhz() {
        for mt76 in [true, false] {
            let mut p = plan_5g();
            p.driver_quirks.mt76 = mt76;
            p.width_mhz = 160;
            let conf = render_hostapd(&p).unwrap();
            let caps = conf.lines().find(|l| l.starts_with("vht_capab=")).unwrap();
            assert!(caps.ends_with("[VHT160]"), "mt76={mt76}: {caps}");
            assert_eq!(caps.matches("VHT160").count(), 1);
            p.width_mhz = 80;
            assert!(!render_hostapd(&p).unwrap().contains("VHT160"));
        }
    }

    #[test]
    fn ht_capab_20mhz_has_no_ht40() {
        let mut p = plan_2g();
        p.width_mhz = 20;
        let conf = render_hostapd(&p).unwrap();
        assert!(!conf.contains("HT40"));
        assert!(!conf.contains("SHORT-GI-40"));
    }

    #[test]
    fn vht_centre_and_chwidth_fixed() {
        let mut p = plan_5g();
        p.channel = Channel::Fixed(149);
        let conf = render_hostapd(&p).unwrap();
        assert!(conf.contains("vht_oper_chwidth=1\n"));
        assert!(conf.contains("vht_oper_centr_freq_seg0_idx=155\n"));
        assert!(conf.contains("he_oper_centr_freq_seg0_idx=155\n"));
        assert!(!conf.contains("[SHORT-GI-160]"));
    }

    #[test]
    fn auto_channel_omits_centre_and_excludes_dfs() {
        let mut p = plan_5g();
        p.channel = Channel::Auto;
        let conf = render_hostapd(&p).unwrap();
        assert!(conf.contains("channel=0\n"));
        assert!(conf.contains("acs_exclude_dfs=1\n"));
        assert!(conf.contains("vht_oper_chwidth=1\n"));
        assert!(!conf.contains("centr_freq_seg0_idx"));
    }

    #[test]
    fn dfs_flags_only_on_5g() {
        let conf = render_hostapd(&plan_2g()).unwrap();
        assert!(!conf.contains("ieee80211h"));
        assert!(!conf.contains("acs_exclude_dfs"));
        assert!(conf.contains("hw_mode=g\n"));
        assert!(
            render_hostapd(&plan_5g())
                .unwrap()
                .contains("ieee80211h=1\n")
        );
    }

    #[test]
    fn standards_gate_their_sections() {
        let mut p = plan_5g();
        p.standards = vec![Standard::N];
        let conf = render_hostapd(&p).unwrap();
        assert!(conf.contains("ieee80211n=1"));
        assert!(!conf.contains("ieee80211ac"));
        assert!(!conf.contains("ieee80211ax"));
        assert!(!conf.contains("he_"));
    }

    #[test]
    fn bss_color_is_stable_and_in_range() {
        for ssid in ["", "a", "Flint2", "Flint2-Guest", "\u{20ac}\u{20ac}"] {
            let color = bss_color(ssid);
            assert!((1..=63).contains(&color), "{ssid:?} -> {color}");
            assert_eq!(color, bss_color(ssid));
        }
        assert_eq!(bss_color("Flint2"), bss_color("Flint2"));
    }

    #[test]
    fn mt76_quirk_selects_capability_set() {
        let mut p = plan_5g();
        let full = render_hostapd(&p).unwrap();
        assert!(full.contains("[MU-BEAMFORMER]"));
        assert!(full.contains("he_mu_beamformer=1"));
        p.driver_quirks.mt76 = false;
        let basic = render_hostapd(&p).unwrap();
        assert!(!basic.contains("BEAMFORMER]"));
        assert!(basic.contains("he_mu_beamformer=0"));
    }

    #[test]
    fn per_bss_options() {
        let mut p = flint2_2g();
        p.aps[1].max_clients = Some(12);
        p.aps[1].mac = Some("02:11:22:33:44:55".parse().unwrap());
        let conf = render_hostapd(&p).unwrap();
        let guest = conf.split("bss=wlan0-1\n").nth(1).unwrap();
        for want in [
            "ignore_broadcast_ssid=1",
            "bridge=br-guest",
            "ap_isolate=1",
            "max_num_sta=12",
            "bssid=02:11:22:33:44:55",
            "wmm_enabled=1",
        ] {
            assert!(guest.contains(want), "missing {want}");
        }
        let main = conf.split("bss=wlan0-1\n").next().unwrap();
        assert!(!main.contains("ap_isolate") && !main.contains("max_num_sta"));
    }

    #[test]
    fn security_open() {
        let mut p = plan_2g();
        p.aps[0].security = Security::Open;
        let conf = render_hostapd(&p).unwrap();
        assert!(conf.contains("wpa=0\nieee80211w=0\n"));
        assert!(!conf.contains("passphrase") && !conf.contains("sae_"));
    }

    #[test]
    fn security_wpa2_psk() {
        let mut p = plan_2g();
        p.aps[0].security = Security::Wpa2Psk {
            passphrase: pass("wpa2-secret-1"),
        };
        let conf = render_hostapd(&p).unwrap();
        for want in [
            "wpa_key_mgmt=WPA-PSK\n",
            "wpa_pairwise=CCMP\n",
            "ieee80211w=1\n",
            "wpa_passphrase=wpa2-secret-1\n",
            "wpa_disable_eapol_key_retries=1\n",
        ] {
            assert!(conf.contains(want), "missing {want}");
        }
        assert!(!conf.contains("sae_"));
    }

    #[test]
    fn security_wpa3_requires_pmf() {
        let conf = render_hostapd(&plan_5g()).unwrap();
        for want in [
            "wpa_key_mgmt=SAE\n",
            "ieee80211w=2\n",
            "sae_password=correct horse\n",
            "sae_require_mfp=1\n",
            "sae_pwe=2\n",
        ] {
            assert!(conf.contains(want), "missing {want}");
        }
        assert!(!conf.contains("wpa_passphrase"));
    }

    #[test]
    fn security_mixed() {
        let conf = render_hostapd(&flint2_2g()).unwrap();
        assert!(conf.contains("wpa_key_mgmt=WPA-PSK SAE\n"));
        assert!(conf.contains("wpa_passphrase=flint2-main-pass\n"));
        assert!(conf.contains("sae_password=flint2-main-pass\n"));
        assert!(conf.contains("ieee80211w=1\n"));
    }

    #[test]
    fn ctrl_dir_is_under_run_dir() {
        assert_eq!(ctrl_dir(), PathBuf::from(format!("{RUN_DIR}/hostapd")));
    }

    #[test]
    fn ctrl_interface_in_every_bss() {
        let conf = render_hostapd(&flint2_2g()).unwrap();
        assert_eq!(
            conf.matches("ctrl_interface=/run/ferritewrt/hostapd\n")
                .count(),
            2
        );
        assert_eq!(conf.matches("ctrl_interface_group=0\n").count(), 2);
    }

    #[test]
    fn six_ghz_sets_op_class() {
        let mut p = plan_5g();
        p.band = Band::G6;
        p.channel = Channel::Fixed(1);
        p.standards = vec![Standard::Ax];
        p.width_mhz = 80;
        let conf = render_hostapd(&p).unwrap();
        assert!(conf.contains("op_class=133\n"));
        assert!(conf.contains("he_oper_centr_freq_seg0_idx=7\n"));
        assert!(!conf.contains("ieee80211h"));
    }
}
