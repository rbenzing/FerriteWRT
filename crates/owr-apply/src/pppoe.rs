//! `Config` -> pppd options for a `PPPoE` WAN (`<run_dir>/pppoe-wan.conf`, 0600).
//!
//! owr-init starts pppd (`pppd file <that file>`) whenever the file exists. pppd reads the
//! image's `/etc/ppp/options` first (`noipdefault`, `maxfail 0`, ...); these lines come
//! later and win. pppd brings up `pppoe-wan`, sets its address and the default route, and
//! writes the ISP's DNS servers to `/etc/ppp/resolv.conf`, which the image links to
//! `<run_dir>/resolv.conf.ppp` for dnsmasq. The WAN port itself only carries the `PPPoE`
//! frames and gets no address.

use std::fmt;

use owr_config::{Config, WanProto};
use zeroize::Zeroizing;

use crate::error::MapError;

/// The interface pppd creates; the firewall's WAN zone covers it.
pub const PPPOE_IFNAME: &str = "pppoe-wan";
/// PPP MTU when the config sets none: 1500 minus the 8-byte `PPPoE` + PPP header.
pub const DEFAULT_MTU: u16 = 1492;
/// `PPPoE` (6 bytes) plus PPP protocol (2 bytes) header.
const PPPOE_OVERHEAD: u16 = 8;
/// Seconds between LCP echo requests, and how many may go unanswered before the link is
/// declared dead; adaptive: only sent when no other traffic arrived.
const LCP_ECHO_INTERVAL: u8 = 1;
const LCP_ECHO_FAILURE: u8 = 5;
/// Seconds before redialling after the link went down.
const HOLDOFF: u8 = 5;

/// pppd's view of a `PPPoE` WAN.
#[derive(Clone, PartialEq, Eq)]
pub struct PppoePlan {
    /// The WAN port the `PPPoE` session runs over.
    pub nic: String,
    pub username: String,
    pub password: Zeroizing<String>,
    /// Access concentrator service name, when the ISP requires one.
    pub service: Option<String>,
    /// PPP MTU and MRU.
    pub mtu: u16,
}

impl fmt::Debug for PppoePlan {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.debug_struct("PppoePlan")
            .field("nic", &self.nic)
            .field("username", &self.username)
            .field("password", &"***")
            .field("service", &self.service)
            .field("mtu", &self.mtu)
            .finish()
    }
}

/// A value pppd will read inside double quotes. `validate_against` already limits the
/// character set; this keeps the options file safe even without it: no control characters
/// (a newline would start a new option), and `\` and `"` are escaped by [`quote`].
fn check_word(field: &str, value: &str) -> Result<(), MapError> {
    if value.is_empty() || value.chars().any(char::is_control) {
        Err(MapError::injection(field))
    } else {
        Ok(())
    }
}

fn quote(value: &str) -> String {
    let mut out = String::with_capacity(value.len().saturating_add(2));
    out.push('"');
    for c in value.chars() {
        if matches!(c, '\\' | '"') {
            out.push('\\');
        }
        out.push(c);
    }
    out.push('"');
    out
}

/// The plan for a `PPPoE` WAN on `wan_dev`; `None` for any other WAN protocol.
pub(crate) fn build_pppoe(cfg: &Config, wan_dev: &str) -> Result<Option<PppoePlan>, MapError> {
    let WanProto::Pppoe {
        username,
        password,
        service,
    } = &cfg.network.wan.proto
    else {
        return Ok(None);
    };
    let path = "network.wan.proto";
    check_word(&format!("{path}.username"), username)?;
    check_word(&format!("{path}.password"), password.expose())?;
    if let Some(s) = service {
        check_word(&format!("{path}.service"), s)?;
    }
    Ok(Some(PppoePlan {
        nic: wan_dev.to_owned(),
        username: username.clone(),
        password: Zeroizing::new(password.expose().to_owned()),
        service: service.clone(),
        mtu: cfg.network.wan.mtu.unwrap_or(DEFAULT_MTU),
    }))
}

/// The MTU the WAN port needs so PPP frames of `mtu` bytes fit (RFC 4638 for more than
/// 1492); `None` leaves the port at its default 1500.
pub(crate) fn port_mtu(mtu: u16) -> Option<u16> {
    (mtu > DEFAULT_MTU).then(|| mtu.saturating_add(PPPOE_OVERHEAD))
}

/// The options file. With `reveal = false` the password is written as `***` (for
/// `render`); only the file pppd reads carries it.
pub fn render_pppoe(plan: &PppoePlan, reveal: bool) -> String {
    let password = if reveal {
        quote(&plan.password)
    } else {
        quote("***")
    };
    let mut l = vec![
        "# Generated by owr-apply. Do not edit; changes are overwritten.".to_owned(),
        "plugin pppoe.so".to_owned(),
        format!("nic-{}", plan.nic),
        format!("ifname {PPPOE_IFNAME}"),
        format!("user {}", quote(&plan.username)),
        format!("password {password}"),
    ];
    if let Some(service) = &plan.service {
        l.push(format!("rp_pppoe_service {}", quote(service)));
    }
    l.extend([
        // The ISP is not asked to authenticate itself to the router.
        "noauth".to_owned(),
        "defaultroute".to_owned(),
        "usepeerdns".to_owned(),
        "persist".to_owned(),
        "maxfail 0".to_owned(),
        format!("holdoff {HOLDOFF}"),
        format!("lcp-echo-interval {LCP_ECHO_INTERVAL}"),
        format!("lcp-echo-failure {LCP_ECHO_FAILURE}"),
        "lcp-echo-adaptive".to_owned(),
        format!("mtu {}", plan.mtu),
        format!("mru {}", plan.mtu),
        // Supervised by owr-init: stay in the foreground, log to stderr (the journal).
        "nodetach".to_owned(),
        "logfd 2".to_owned(),
    ]);
    let mut text = l.join("\n");
    text.push('\n');
    text
}

#[cfg(test)]
mod tests {
    use super::*;

    fn plan(password: &str, service: Option<&str>) -> PppoePlan {
        PppoePlan {
            nic: "eth1".to_owned(),
            username: "user@isp".to_owned(),
            password: Zeroizing::new(password.to_owned()),
            service: service.map(str::to_owned),
            mtu: DEFAULT_MTU,
        }
    }

    #[test]
    fn options_name_the_port_interface_credentials_and_keepalive() {
        let text = render_pppoe(&plan("s3cret pw", Some("fibre")), true);
        let lines: Vec<&str> = text.lines().collect();
        for want in [
            "plugin pppoe.so",
            "nic-eth1",
            "ifname pppoe-wan",
            "user \"user@isp\"",
            "password \"s3cret pw\"",
            "rp_pppoe_service \"fibre\"",
            "noauth",
            "defaultroute",
            "usepeerdns",
            "persist",
            "maxfail 0",
            "lcp-echo-interval 1",
            "lcp-echo-failure 5",
            "mtu 1492",
            "mru 1492",
            "nodetach",
            "logfd 2",
        ] {
            assert!(lines.contains(&want), "missing {want:?} in\n{text}");
        }
        assert!(!text.contains("rp_pppoe_service") || text.contains("fibre"));
        assert!(!render_pppoe(&plan("x", None), true).contains("rp_pppoe_service"));
    }

    #[test]
    fn the_password_is_only_in_the_file_pppd_reads() {
        let p = plan("s3cret", None);
        assert!(!render_pppoe(&p, false).contains("s3cret"));
        assert!(render_pppoe(&p, false).contains("password \"***\""));
        assert!(!format!("{p:?}").contains("s3cret"));
    }

    #[test]
    fn quotes_and_backslashes_are_escaped_and_control_characters_refused() {
        assert_eq!(quote(r#"a"b\c"#), r#""a\"b\\c""#);
        let text = render_pppoe(&plan(r#"p"w\"#, None), true);
        assert!(text.lines().any(|l| l == r#"password "p\"w\\""#), "{text}");

        for bad in ["", "a\nnoauth", "a\rb", "a\0b", "tab\there"] {
            assert!(
                matches!(check_word("f", bad), Err(MapError::Injection { .. })),
                "{bad:?}"
            );
        }
        assert_eq!(check_word("f", "user@isp.example"), Ok(()));
    }

    #[test]
    fn the_port_mtu_grows_only_for_baby_jumbo_frames() {
        assert_eq!(port_mtu(1492), None);
        assert_eq!(port_mtu(1400), None);
        assert_eq!(port_mtu(1500), Some(1508));
    }
}
